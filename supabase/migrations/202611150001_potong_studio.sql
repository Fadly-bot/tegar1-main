-- Potong Studio tables are prefixed to keep them isolated from other apps
-- already using the selected Supabase project.
create table if not exists public.potong_users (
  id bigint generated by default as identity primary key,
  username varchar(80) not null unique,
  password_hash text not null,
  name varchar(160) not null,
  email varchar(190) not null,
  role varchar(16) not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.potong_orders (
  id bigint generated by default as identity primary key,
  code varchar(32) not null unique,
  user_id bigint not null references public.potong_users(id) on delete restrict,
  package varchar(80) not null,
  price integer not null check (price >= 0),
  deadline varchar(80) not null default 'Fleksibel',
  drive_url varchar(2048) not null default '',
  notes text not null default '',
  admin_notes varchar(3000) not null default '',
  status varchar(32) not null default 'Menunggu konfirmasi'
    check (status in ('Menunggu konfirmasi', 'Dalam pengerjaan', 'Selesai')),
  created_at timestamptz not null default now()
);

create index if not exists idx_potong_orders_user_created
  on public.potong_orders (user_id, created_at desc);
create index if not exists idx_potong_orders_created
  on public.potong_orders (created_at desc);

create table if not exists public.potong_sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.potong_users(id) on delete cascade,
  token_hash char(64) not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

alter table public.potong_users enable row level security;
alter table public.potong_orders enable row level security;
alter table public.potong_sessions enable row level security;

revoke all on public.potong_users, public.potong_orders, public.potong_sessions from anon, authenticated;
grant all on public.potong_users, public.potong_orders, public.potong_sessions to service_role;
grant usage, select on sequence public.potong_users_id_seq, public.potong_orders_id_seq, public.potong_sessions_id_seq to service_role;
